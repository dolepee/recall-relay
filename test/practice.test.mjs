async function workspace(now=()=>NOW){
  const dir=await mkdtemp(join(tmpdir(),'relay-practice-'));
  const path=join(dir,'practice.sqlite');
  return {dir,path,open:(options={})=>new PracticeWorkspace({path,now,...options})};
}

async function ready(ws,session){
  ws.role(session,'customer');
  let view=ws.submit(session,{...bind(ws.view(session)),lot:'LOT-A',acknowledged:true,photo:PHOTO_A,extra:extra()});
  ws.role(session,'merchant');
  return ws.review(session,{...bind(view),confirmed:true});
}

test('one practice session runs the full journey and a correction invalidates review',async()=>{
  const space=await workspace();
  const ws=space.open();
  try{
    const {session,token}=ws.open(null);
    assert.match(token,/^[\w-]{43}$/);
    let view=ws.view(session);
    assert.equal(view.role,'customer');
    assert.equal(view.case.status.code,'AWAITING_CUSTOMER');
    assert.equal(view.scenario.affectedCents,2599);
    assert.equal(view.scenario.unaffectedCents,3400);
    assert.equal(view.scenario.totalCents,5999);
    assert.ok(view.scenario.requirements.every(r=>r.quote&&r.citation));
    assert.match(view.scenario.sourceNote,/not a CPSC/);
    assert.equal(view.scenario.exampleDraft.label,'Example suggested requirements');
    assert.match(view.scenario.exampleDraft.note,/not generated by a live model/);
    assert.equal(practiceFixture.exampleDraft.label,'Example suggested requirements');

    ws.role(session,'merchant');
    assert.throws(()=>ws.submit(session,{...bind(view),lot:'LOT-A',acknowledged:true,photo:PHOTO_A,extra:extra()}),/customer view/);
    ws.role(session,'customer');
    assert.throws(()=>ws.requestChanges(session,{...bind(view),message:'x'.repeat(20),replacePhoto:true}),/merchant view/);

    view=ws.submit(session,{...bind(view),lot:'LOT-A',acknowledged:true,photo:PHOTO_A,extra:extra()});
    assert.equal(view.case.status.code,'SUBMITTED');
    assert.deepEqual(view.case.missing,[]);
    assert.equal(view.case.submission.lot,'LOT-A');

    ws.role(session,'merchant');
    view=ws.review(session,{...bind(view),confirmed:true});
    assert.equal(view.case.plan.status,'READY_FOR_APPROVAL');
    assert.equal(view.case.review.revision,view.case.revision);
    assert.match(view.case.plan.digest,/^[a-f0-9]{64}$/);

    view=ws.requestChanges(session,{...bind(view),message:'The lot code is too blurred to read. Please upload a clearer photograph.',replacePhoto:true});
    assert.equal(view.case.review,null,'a correction must clear the prior review');
    assert.notEqual(view.case.plan.status,'READY_FOR_APPROVAL');
    assert.equal(view.case.plan.digest,null);
    assert.equal(view.case.status.code,'NEEDS_INFORMATION');
    await assert.rejects(ws.approve(session,{...bind(view),confirmed:true,digest:null}),/requested changes/);

    ws.role(session,'customer');
    view=ws.submit(session,{...bind(view),lot:'LOT-A',acknowledged:true,photo:PHOTO_B,extra:extra(),correctionResponse:'I uploaded a clearer label photograph showing LOT-A.'});
    assert.equal(view.case.correction.state,'RESPONDED');
    assert.equal(view.case.review,null);

    ws.role(session,'merchant');
    view=ws.review(session,{...bind(view),confirmed:true});
    const approved=await ws.approve(session,{...bind(view),confirmed:true,digest:view.case.plan.digest});
    assert.equal(approved.case.status.code,'COMPLETED');
    assert.equal(approved.case.refund.state,'COMPLETED');
    assert.equal(approved.case.refund.cents,2599);
    assert.equal(approved.case.refund.currency,'USD');
    assert.match(approved.case.refund.reference,/^PRACTICE-REFUND-/);
    assert.equal(approved.case.unresolved,null);
    assert.match(approved.case.status.reason,/No payment provider was contacted/);
    assert.match(approved.case.status.reason,/no funds moved/);

    ws.close();
    const reopened=space.open();
    try{
      const again=reopened.open(token).session;
      const stored=reopened.view(again);
      assert.equal(stored.case.status.code,'COMPLETED');
      assert.equal(stored.case.refund.reference,approved.case.refund.reference);
      assert.equal(stored.case.revision,approved.case.revision);
      assert.equal(stored.attempt,1);
    }finally{reopened.close();}
  } finally { try{ws.close();}catch{} await rm(space.dir,{recursive:true,force:true}); }
});

test('stale attempt, case, revision and digest requests are rejected without side effects',async()=>{
  const space=await workspace();
  const ws=space.open();
  try{
    const {session}=ws.open(null);
    let view=await ready(ws,session);
    const shown={...bind(view),confirmed:true,digest:view.case.plan.digest};

    // A newer review changes the digest; the old page must not approve it.
    ws.requestChanges(session,{...bind(view),message:'Please send a clearer photograph of the lot code.',replacePhoto:true});
    ws.role(session,'customer');
    view=ws.submit(session,{...bind(ws.view(session)),lot:'LOT-A',acknowledged:true,photo:PHOTO_B,extra:extra(),correctionResponse:'New clearer photograph attached.'});
    ws.role(session,'merchant');
    view=ws.review(session,{...bind(view),confirmed:true});
    const before=count(ws,'refunds');
    await assert.rejects(ws.approve(session,{...shown}),StaleActionError);
    assert.equal(count(ws,'refunds'),before,'a stale digest must not reserve or settle anything');

    // A stale revision is rejected by the core gate as well.
    assert.throws(()=>ws.review(session,{...bind(view),revision:shown.revision,confirmed:true}),StaleActionError);

    // After restart the old case identity is stale even with a valid revision.
    const oldCase={...bind(view),confirmed:true,digest:view.case.plan.digest};
    const restarted=ws.restart(session);
    assert.notEqual(restarted.case.id,view.case.id);
    assert.equal(restarted.role,'customer');
    ws.role(session,'merchant'); // Exercise the stale identity guard independently of the role guard.
    await assert.rejects(ws.approve(session,{...oldCase}),StaleActionError);
    assert.throws(()=>ws.review(session,{...oldCase}),StaleActionError);
    assert.equal(count(ws,'refunds'),0);
  } finally { ws.close(); await rm(space.dir,{recursive:true,force:true}); }
});

test('a persisted unresolved reservation is never shown as a completed receipt',async()=>{
  const space=await workspace();
  const ws=space.open();
  try{
    const {session,token}=ws.open(null);
    let view=await ready(ws,session);
    const claim=ws.desk.claim(session.claimId);
    const plan=ws.desk.plan(claim);
    ws.desk.journal.reserve(plan,{actor:'local-merchant',digest:plan.digest},5999);

    view=ws.view(session);
    assert.equal(view.case.refund,null,'RESERVED is not a receipt');
    assert.equal(view.case.unresolved.state,'RESERVED');
    assert.notEqual(view.case.status.code,'COMPLETED');
    assert.match(view.case.status.reason,/not recorded/i);
    const stored=JSON.parse(ws.desk.db.prepare('SELECT data FROM practice_sessions WHERE token_hash=?').get(createHash('sha256').update(token).digest('hex')).data);
    assert.equal(ws.view({...stored,token}).case.unresolved.state,'RESERVED');

    const resumed=await ws.resume(session,{...bind(view),digest:view.case.plan.digest});
    assert.equal(resumed.case.status.code,'COMPLETED');
    assert.equal(resumed.case.unresolved,null);
    assert.match(resumed.case.refund.reference,/^PRACTICE-REFUND-/);
  } finally { ws.close(); await rm(space.dir,{recursive:true,force:true}); }
});

test('restart clears the old claim, photos and journal rows and caps attempts',async()=>{
  const space=await workspace();
  const ws=space.open();
  try{
    const {session}=ws.open(null);
    let view=await ready(ws,session);
    await ws.approve(session,{...bind(view),confirmed:true,digest:view.case.plan.digest});
    assert.equal(count(ws,'claims'),1);
    assert.equal(count(ws,'refunds'),1);
    const first=view.case.id;
    view=ws.restart(session);
    assert.notEqual(view.case.id,first);
    assert.equal(count(ws,'claims'),1,'the old claim and photo are removed');
    assert.equal(count(ws,'refunds'),0,'the old journal row is removed');
    assert.equal(count(ws,'refund_hints'),0);
    assert.equal(view.attempt,2);
    assert.equal(view.case.status.code,'AWAITING_CUSTOMER');

    assert.equal(view.role,'customer');
    for(let i=2;i<10;i++){ws.role(session,'merchant');view=ws.restart(session);}
    assert.equal(view.attempt,10);
    ws.role(session,'merchant');
    assert.throws(()=>ws.restart(session),/restart limit/);
  } finally { ws.close(); await rm(space.dir,{recursive:true,force:true}); }
});

test('an expired session is purged and must start fresh',async()=>{
  let clock=Date.parse(NOW);
  const space=await workspace(()=>new Date(clock).toISOString());
  const ws=space.open();
  try{
    const {token}=ws.open(null);
    ws.role(ws.open(token).session,'customer');
    clock+=practiceFixture.SESSION_TTL_MS+1000;
    assert.throws(()=>ws.open(token),ExpiredSessionError);
    assert.equal(count(ws,'practice_sessions'),0,'expired session removed');
    assert.equal(count(ws,'claims'),0,'expired claim and photo removed');
    const fresh=ws.new(token);
    assert.equal(fresh.fresh,true);
    assert.equal(fresh.session.role,'customer');
  } finally { ws.close(); await rm(space.dir,{recursive:true,force:true}); }
});

test('practice HTTP routes validate before creating state and map stale, expired and new',async()=>{
  let clock=Date.parse(NOW);
  const space=await workspace(()=>new Date(clock).toISOString());
  const ws=space.open();
  try{
    const origin='http://127.0.0.1:4321';
    let captured;
    const res={headers:{},setHeader(k,v){this.headers[k]=v;}};
    const json=(r,status,value)=>{captured={status,value,headers:{...r.headers}};};
    let bodyValue={},bodyError=null;
    const route=practiceRoutes(ws,{json,body:async()=>{if(bodyError)throw bodyError;return bodyValue;},origin});
    async function call(method,path,{cookie,body={},origin:o=origin,contentType='application/json',failure}={}){
      captured=undefined;res.headers={};bodyValue=body;bodyError=failure||null;
      const req={method,headers:{origin:o,'content-type':contentType,...(cookie?{cookie:`rr_practice=${cookie}`}:{})}};
      await route(req,res,path);
      return {...captured,setCookie:captured?.headers['Set-Cookie']||res.headers['Set-Cookie']};
    }

    assert.equal(count(ws,'practice_sessions'),0);
    assert.equal((await call('GET','/api/practice/nope')).status,404);
    assert.equal(count(ws,'practice_sessions'),0,'an unknown route must not create a session');
    assert.equal((await call('POST','/api/practice/unknown',{body:{}})).status,404);
    assert.equal((await call('PUT','/api/practice/state')).status,405);
    assert.equal((await call('POST','/api/practice/submit',{failure:new Error('Request is too large.'),body:{}})).status,400);
    assert.equal(count(ws,'practice_sessions'),0,'an oversized body must not create a session');
    assert.equal((await call('POST','/api/practice/role',{origin:'http://evil.test',body:{role:'customer'}})).status,403);

    const first=await call('GET','/api/practice/state');
    assert.equal(first.status,200);
    assert.match(first.setCookie,/rr_practice=[\w-]{43}/);
    const token=/rr_practice=([\w-]{43})/.exec(first.setCookie)[1];

    let result=await call('POST','/api/practice/role',{cookie:token,body:{role:'customer'}});
    let view=result.value;
    result=await call('POST','/api/practice/submit',{cookie:token,body:{...bind(view),lot:'LOT-A',acknowledged:true,photo:PHOTO_A,extra:extra()}});
    assert.equal(result.value.case.status.code,'SUBMITTED');
    result=await call('POST','/api/practice/role',{cookie:token,body:{role:'merchant'}});
    view=result.value;
    result=await call('POST','/api/practice/review',{cookie:token,body:{...bind(view),confirmed:true}});
    assert.equal(result.value.case.plan.status,'READY_FOR_APPROVAL');
    const shown=result.value;
    ws.requestChanges(ws.open(token).session,{...bind(shown),message:'Please send a clearer photograph of the lot code.',replacePhoto:true});

    const stale=await call('POST','/api/practice/review',{cookie:token,body:{...bind(shown),confirmed:true}});
    assert.equal(stale.status,409);
    assert.equal(stale.value.stale,true);
    assert.match(stale.value.error,/Refresh/);

    const unknown=await call('GET','/api/practice/state',{cookie:'x'.repeat(43)});
    assert.equal(unknown.status,410);
    assert.equal(unknown.value.expired,true);
    assert.match(unknown.setCookie,/Max-Age=0/);

    const fresh=await call('POST','/api/practice/new',{cookie:token,body:{}});
    assert.equal(fresh.status,200);
    assert.equal(count(ws,'practice_sessions'),1,'a fresh start replaces the old session');
    const token2=/rr_practice=([\w-]{43})/.exec(fresh.setCookie)[1];
    clock+=practiceFixture.SESSION_TTL_MS+1000;
    const expired=await call('GET','/api/practice/state',{cookie:token2});
    assert.equal(expired.status,410);
    assert.equal(expired.value.expired,true);
  } finally { ws.close(); await rm(space.dir,{recursive:true,force:true}); }
});

