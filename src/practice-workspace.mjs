function campaign() {
  return {
    ...notice,
    requirements: notice.requirements.map(field => field.quote),
    fields: notice.requirements.map(({id, kind, quote}) => ({id, kind, quote, sourceUrl: notice.sourceUrl})),
  };
}

function newClaim(now) {
  const id = randomUUID();
  return {
    id,
    campaign: campaign(),
    access: secret(),
    createdAt: now,
    purchase: {
      id: `PRACTICE-${id.slice(0, 8).toUpperCase()}`,
      version: 1,
      merchantId: notice.settlingMerchantId,
      captureId: `PRACTICE-CAPTURE-${id}`,
      lineId: `${notice.sku}-LINE`,
      sku: notice.sku,
      lot: notice.lot,
      capturedAt: now,
      currency: 'USD',
      linePaidCents: AFFECTED_CENTS,
      lineRefundedCents: 0,
      captureRemainingCents: TOTAL_CENTS,
    },
    submission: null,
    correction: null,
    revision: 0,
    review: null,
  };
}

// Injected journal or a local file. The connected workspace never shares this
// store, and a cloud host can pass a SQLite-backed journal from its own object.
export class PracticeWorkspace {
  constructor({journal, path = ':memory:', origin = 'http://127.0.0.1:4318', now = () => new Date().toISOString(), provider = () => new SimulatedRefundProvider(), ttlMs = SESSION_TTL_MS} = {}) {
    this.now = now;
    this.ttlMs = Number.isFinite(ttlMs) && ttlMs > 0 ? ttlMs : SESSION_TTL_MS;
    this.ownsJournal = !journal;
    this.desk = new ClaimDeskCore({
      journal: journal || new RefundJournal(path),
      origin,
      now,
      provider,
    });
    // The practice notice is reviewed by construction; customer evidence still
    // needs its own recorded review before a simulated refund is allowed.
    this.desk.setSetting('published', 'yes');
    this.desk.db.exec('CREATE TABLE IF NOT EXISTS practice_sessions (token_hash TEXT PRIMARY KEY, data TEXT NOT NULL, created_at TEXT NOT NULL)');
  }

  // Explicit fresh start: drop any current session instead of accumulating it.
  // A host may pass the token it will set as the cookie, so the DO and the
  // browser agree on the same session from the first request.
  new(preferred) {
    const token = typeof preferred === 'string' && TOKEN.test(preferred) ? preferred : secret();
    try {
      const {session} = this.open(token);
      this.removeSession(hash(token), session);
    } catch {}
    const claim = newClaim(this.now());
    const session = {claimId: claim.id, role: 'merchant', attempt: 1, createdAt: this.now(), token};
    this.desk.saveClaim(claim);
    this.save(session);
    return {session, fresh: true, token};
  }

  open(token) {
    this.purgeExpired();
    if (token !== undefined && token !== null) {
      if (typeof token !== 'string' || !TOKEN.test(token)) throw new PracticeSessionError('Invalid practice session.');
      const row = this.desk.db.prepare('SELECT data FROM practice_sessions WHERE token_hash=?').get(hash(token));
      if (!row) throw new ExpiredSessionError('This practice session has expired.');
      const session = JSON.parse(row.data);
      if (this.expired(session)) {
        this.removeSession(hash(token), session);
        throw new ExpiredSessionError('This practice session has expired.');
      }
      session.token = token;
      return {session, fresh: false};
    }
    const freshToken = secret();
    const claim = newClaim(this.now());
    const session = {claimId: claim.id, role: 'merchant', attempt: 1, createdAt: this.now()};
    this.desk.saveClaim(claim);
    session.token = freshToken;
    this.save(session);
    return {session, fresh: true, token: freshToken};
  }

  expired(session) {
    const created = Date.parse(session.createdAt);
    return !Number.isFinite(created) || Date.parse(this.now()) - created >= this.ttlMs;
  }

  purgeExpired() {
    const rows = this.desk.db.prepare('SELECT token_hash, data FROM practice_sessions').all();
    for (const row of rows) {
      const session = JSON.parse(row.data);
      if (this.expired(session)) this.removeSession(row.token_hash, session);
    }
  }

  removeSession(tokenHash, session) {
    this.deleteCaseData(session.claimId);
    this.desk.db.prepare('DELETE FROM practice_sessions WHERE token_hash=?').run(tokenHash);
  }

  // Restart and expiry must not accumulate photos, claims or journal rows.
  deleteCaseData(claimId) {
    let claim;
    try { claim = this.desk.claim(claimId); } catch { return; }
    const capture = claim.purchase.captureId;
    const requestIds = this.desk.db.prepare('SELECT request_id FROM refunds WHERE capture=?').all(capture).map(row => row.request_id);
    for (const requestId of requestIds) this.desk.db.prepare('DELETE FROM refund_hints WHERE request_id=?').run(requestId);
    this.desk.db.prepare('DELETE FROM refunds WHERE capture=?').run(capture);
    this.desk.db.prepare('DELETE FROM claims WHERE id=?').run(claimId);
  }

  save(session) {
    const {token} = session;
    if (typeof token !== 'string' || !TOKEN.test(token)) throw new PracticeSessionError('Invalid practice session.');
    const {token: _omitted, ...data} = session;
    this.desk.db.prepare('INSERT INTO practice_sessions VALUES (?,?,?) ON CONFLICT(token_hash) DO UPDATE SET data=excluded.data')
      .run(hash(token), JSON.stringify(data), session.createdAt);
  }

  claim(session) {
    try {
      return this.desk.claim(session.claimId);
    } catch {
      throw new ExpiredSessionError('This practice case is no longer available. Start a new one.');
    }
  }

  // Every mutation is bound to the attempt, case and revision the browser showed.
  assertCurrent(session, input, claim) {
    if (input.caseId !== claim.purchase.id || Number(input.attempt) !== session.attempt || Number(input.revision) !== claim.revision)
      throw new StaleActionError('This practice case changed. Refresh the practice case before trying again.');
  }

  role(session, role) {
    if (!ROLES.has(role)) throw new Error('Choose the merchant or customer view.');
    session.role = role;
    this.save(session);
    return this.view(session);
  }

  submit(session, input) {
    if (session.role !== 'customer') throw new Error('Switch to the customer view to submit evidence.');
    const claim = this.claim(session);
    this.assertCurrent(session, input, claim);
    if (claim.revision >= MAX_REVISION) throw new Error('This practice case has reached its submission limit. Start a new practice case.');
    this.desk.submit(claim.access, input);
    return this.view(session);
  }

  requestChanges(session, input) {
    if (session.role !== 'merchant') throw new Error('Switch to the merchant view to request a correction.');
    const claim = this.claim(session);
    this.assertCurrent(session, input, claim);
    this.desk.requestChanges(session.claimId, {
      revision: input.revision,
      message: input.message,
      replacePhoto: input.replacePhoto,
    });
    return this.view(session);
  }

  review(session, input) {
    if (session.role !== 'merchant') throw new Error('Switch to the merchant view to review evidence.');
    const claim = this.claim(session);
    this.assertCurrent(session, input, claim);
    this.desk.review(session.claimId, {revision: input.revision, confirmed: input.confirmed});
    return this.view(session);
  }

  async approve(session, input) {
    if (session.role !== 'merchant') throw new Error('Switch to the merchant view to record a simulated refund.');
    if (input.confirmed !== true) throw new Error('Confirm the simulated refund explicitly.');
    const claim = this.claim(session);
    this.assertCurrent(session, input, claim);
    const plan = this.desk.plan(claim);
    if (plan.status !== 'READY_FOR_APPROVAL')
      throw new Error(plan.reason || 'Review the current evidence before recording a simulated refund.');
    if (typeof input.digest !== 'string' || input.digest !== plan.digest)
      throw new StaleActionError('This approval does not match the plan shown. Refresh the practice case before trying again.');
    await this.desk.approve(session.claimId, {digest: plan.digest});
    return this.view(session);
  }

  async resume(session, input) {
    if (session.role !== 'merchant') throw new Error('Switch to the merchant view to resume a simulated refund.');
    const claim = this.claim(session);
    this.assertCurrent(session, input, claim);
    const reservation = this.desk.reservation(claim);
    if (!reservation) throw new Error('There is no practice refund to resume.');
    if (reservation.state !== 'RESERVED')
      throw new Error('This practice refund cannot be resumed safely. Start a new practice case.');
    const plan = this.desk.plan(claim);
    if (plan.status !== 'READY_FOR_APPROVAL' || input.digest !== plan.digest)
      throw new StaleActionError('This practice case changed. Refresh the practice case before trying again.');
    await this.desk.approve(session.claimId, {digest: plan.digest});
    return this.view(session);
  }

  restart(session) {
    if (session.role !== 'merchant') throw new Error('Switch to the merchant view to start a new practice case.');
    if (session.attempt >= MAX_ATTEMPTS) throw new Error('This practice session has reached its restart limit. Open a fresh practice session.');
    this.deleteCaseData(session.claimId);
    const claim = newClaim(this.now());
    this.desk.saveClaim(claim);
    session.claimId = claim.id;
    session.attempt += 1;
    this.save(session);
    return this.view(session);
  }

  status(claim, reservation, missing, plan) {
    if (reservation) {
      const code = reservation.state;
      const reason = code === 'COMPLETED'
        ? 'Simulated refund recorded on this practice case. No payment provider was contacted and no funds moved.'
        : code === 'RESERVED'
          ? 'A simulated refund is prepared but not recorded. No funds moved; resume or start a new case.'
          : 'A simulated refund attempt is unresolved. No funds moved; start a new case.';
      return {code, reason};
    }
    if (!claim.submission) return {code: 'AWAITING_CUSTOMER', reason: 'Complete the practice claim to continue.'};
    if (claim.correction?.state === 'REQUESTED')
      return {code: 'NEEDS_INFORMATION', reason: 'The merchant requested a change. Read the message and update the claim.'};
    if (missing.length) return {code: 'NEEDS_INFORMATION', reason: 'The claim is saved. Add the missing information.'};
    if (claim.submission.lot !== notice.lot)
      return {code: 'MANUAL', reason: 'The lot differs from the practice notice. The merchant reviews it manually.'};
    if (plan.status === 'MANUAL')
      return {code: 'MANUAL', reason: plan.reason};
    if (claim.review) return {code: plan.status, reason: 'Evidence reviewed for this version. Waiting for the merchant’s simulated refund decision.'};
    return {code: 'SUBMITTED', reason: 'The claim is with the merchant for review.'};
  }

  view(session) {
    const claim = this.claim(session);
    const reservation = this.desk.reservation(claim);
    const missing = this.desk.missing(claim);
    const plan = this.desk.plan(claim);
    const correction = claim.correction ? (({photoHash, ...visible}) => visible)(claim.correction) : null;
    const status = this.status(claim, reservation, missing, plan);
    const review = claim.review && claim.review.revision === claim.revision
      ? {revision: claim.review.revision, reviewedAt: claim.review.reviewedAt}
      : null;
    const completed = reservation?.state === 'COMPLETED';
    return {
      mode: 'practice',
      simulated: true,
      role: session.role,
      attempt: session.attempt,
      scenario: {
        title: notice.title,
        product: notice.product,
        sku: notice.sku,
        lot: notice.lot,
        notice: notice.notice,
        sourceLabel: notice.sourceLabel,
        sourceNote: notice.sourceNote,
        requirements: notice.requirements,
        exampleDraft,
        totalCents: TOTAL_CENTS,
        affectedCents: AFFECTED_CENTS,
        unaffectedCents: UNAFFECTED_CENTS,
      },
      case: {
        id: claim.purchase.id,
        revision: claim.revision,
        status,
        missing,
        plan: {status: plan.status, reason: plan.reason, digest: plan.status === 'READY_FOR_APPROVAL' ? plan.digest : null},
        review,
        correction,
        locked: Boolean(reservation),
        submittedAt: claim.submission?.submittedAt || null,
        submission: claim.submission
          ? {lot: claim.submission.lot, acknowledged: claim.submission.acknowledged, hasPhoto: Boolean(claim.submission.photo), extra: claim.submission.extra || {}}
          : null,
        photo: claim.submission?.photo || null,
        refund: completed
          ? {state: reservation.state, cents: reservation.cents, currency: reservation.currency, reference: reservation.refund_id, simulated: true}
          : null,
        unresolved: reservation && !completed
          ? {state: reservation.state, cents: reservation.cents, currency: reservation.currency}
          : null,
      },
      boundary: {
        storage: 'Practice data stays with this browser session in its own store.',
        provider: 'No payment provider is connected and no funds move.',
        assistant: 'No live model calls; the suggested requirements shown are example fixture text.',
      },
    };
  }

  close() {
    if (this.ownsJournal) this.desk.close();
  }
}

